function escapeAttribute(value) {
  return String(value).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

function svgElement([tag, attributes]) {
  const serialized = Object.entries(attributes)
    .filter(([name]) => name !== 'key')
    .map(([name, value]) => `${name.replace(/[A-Z]/g, letter => `-${letter.toLowerCase()}`)}="${escapeAttribute(value)}"`)
    .join(' ');
  return `<${tag} ${serialized}/>`;
}

const symbols = Object.entries(icons).map(([name, nodes]) =>
  `<symbol id="hg-${name}" viewBox="0 0 24 24" fill="none">\n${nodes.map(svgElement).join('\n')}\n</symbol>`
);
