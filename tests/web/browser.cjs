const assert = require('node:assert/strict');
const { chromium } = require('playwright');

(async () => {
  const base = process.argv[2];
  const browser = await chromium.launch();
  const errors = [];
  const context = await browser.newContext();
  const observe = page => page.on('pageerror', error => errors.push(error.message));
  context.on('page', observe);
  const page = await context.newPage();
  page.on('dialog', dialog => dialog.accept());
  const signIn = async (target, username, password) => {
    await target.goto(`${base}/login`);
    await target.getByLabel('Username', {exact: true}).fill(username);
    await target.getByLabel('Password', {exact: true}).fill(password);
    await target.getByRole('button', {name: 'Sign in', exact: true}).click();
    await target.locator('#music-player').waitFor();
  };
  try {
    await page.goto(base);
    await page.getByRole('button', {name: 'Sign in', exact: true}).waitFor();
    await page.getByLabel('Username', {exact: true}).fill('admin');
    await page.getByLabel('Password', {exact: true}).fill('wrong-password');
    await page.getByRole('button', {name: 'Sign in', exact: true}).click();
    await page.getByRole('alert').waitFor();
    await signIn(page, 'admin', 'admin');
    await page.locator('#bootstrap-warning').waitFor();
    await page.getByRole('link', {name: 'Settings', exact: false}).click();
    await page.locator('#create-user-form').waitFor();
    await page.locator('#create-user-form [name="username"]').fill('bad name');
    await page.locator('#create-user-form [name="password"]').fill('password');
    assert.equal(await page.locator('#create-user-form').evaluate(form => form.checkValidity()), false, 'username validation must reject spaces');
    for (const username of ['alice', 'bob']) {
      await page.locator('#create-user-form [name="username"]').fill(username);
      await page.locator('#create-user-form [name="password"]').fill('password');
      await page.locator('#create-user-form button').click();
      await page.locator(`.user-row[data-username="${username}"]`).waitFor();
    }
    const aliceContext = await browser.newContext();
    aliceContext.on('page', observe);
    const alice = await aliceContext.newPage();
    alice.on('dialog', dialog => dialog.accept());
    await signIn(alice, 'alice', 'password');
    assert.equal(await alice.locator('.library li[data-id]').count(), 0, 'personal playlist must not contain admin tracks');
    await alice.getByRole('link', {name: 'Server tracks', exact: false}).click();
    await alice.locator('.library li[data-id]').first().waitFor();
    assert.notEqual(await alice.locator('.sidebar nav a[href="/?source=all"]').evaluate(link => getComputedStyle(link).backgroundColor), 'rgba(0, 0, 0, 0)', 'the shared-catalogue link must be selected after navigation');
    assert.equal(await alice.locator('.sidebar nav a[href="/"]').evaluate(link => getComputedStyle(link).backgroundColor), 'rgba(0, 0, 0, 0)', 'the previous page must not remain selected');
    assert.equal(await alice.locator('.library li[data-id]').count(), 2);
    await alice.locator('.play-track').first().click();
    await alice.waitForFunction(() => document.getElementById('player-audio').currentTime > 0.5);
    await alice.evaluate(() => {
      window.originalAudio = document.getElementById('player-audio');
      window.seekEvents = 0;
      originalAudio.addEventListener('seeking', () => window.seekEvents++);
    });
    const secondTab = await aliceContext.newPage();
    await secondTab.goto(base);
    assert.equal(await secondTab.locator('#player-audio').evaluate(audio => audio.paused), true, 'opening a tab must not autoplay');
    await secondTab.locator('#player-toggle').click();
    await secondTab.waitForFunction(() => document.getElementById('player-audio').currentTime > 0.2);
    assert.equal(await alice.locator('#player-audio').evaluate(audio => audio.paused), false, 'another tab must not take playback ownership');
    await secondTab.locator('#player-toggle').click();
    assert.equal(await alice.locator('#player-audio').evaluate(audio => audio.paused), false, 'another tab must not pause this tab');
    await alice.locator('#player-volume').evaluate(input => { input.value=37; input.dispatchEvent(new Event('input', {bubbles:true})); });
    await alice.locator('#player-mute').click();
    assert.equal(await alice.locator('#player-audio').evaluate(audio => audio.muted), true);
    await alice.locator('#player-mute').click();
    assert.equal(await alice.locator('#player-audio').evaluate(audio => audio.volume), 0.37, 'unmute must retain volume');
    await alice.locator('#player-shuffle').click();
    await alice.waitForFunction(() => document.getElementById('player-shuffle').getAttribute('aria-pressed') === 'true');
    assert.equal(await alice.evaluate(() => window.seekEvents), 0, 'shuffle must not seek current audio');
    assert.equal(await alice.locator('#player-audio').evaluate(audio => audio.paused), false);
    await alice.getByRole('link', {name: 'Settings', exact: false}).click();
    await alice.locator('#create-user-form').waitFor();
    assert.equal(await alice.evaluate(() => window.originalAudio === document.getElementById('player-audio') && !originalAudio.paused), true, 'navigation must preserve audio');
    for (const theme of ['light', 'dark']) {
      await alice.evaluate(theme => document.documentElement.dataset.theme = theme, theme);
      assert.notEqual(await alice.locator('.users-panel').evaluate(el => getComputedStyle(el).backgroundColor), 'rgba(0, 0, 0, 0)');
    }
    await alice.setViewportSize({width:390, height:844});
    assert.equal(await alice.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, 'settings must fit a narrow screen');
    await alice.locator('#player-toggle').click();
    assert.equal(await alice.locator('#player-audio').evaluate(audio => audio.paused), true);
    await alice.getByRole('link', {name: 'Server tracks', exact: false}).click();
    await alice.locator('.library li[data-id]').first().waitFor();
    assert.equal((await aliceContext.request.post(`${base}/fixture/invalidate`)).status(), 204);
    await alice.evaluate(() => document.dispatchEvent(new CustomEvent('htmx:afterSwap', {detail:{target:document.getElementById('content')}})));
    await alice.waitForFunction(() => [...document.querySelectorAll('.play-track')].every(button => button.disabled));
    assert.equal(await alice.locator('.download-track[aria-disabled="true"]').count(), 2, 'invalidated files must lose download actions without a page reload');
    const recoveryProblems = [];
    assert.equal((await aliceContext.request.post(`${base}/fixture/restore`)).status(), 204);
    await alice.evaluate(() => document.dispatchEvent(new CustomEvent('htmx:afterSwap', {detail:{target:document.getElementById('content')}})));
    await alice.waitForFunction(() => [...document.querySelectorAll('.play-track')].every(button => !button.disabled), undefined, {timeout:3000}).catch(() => recoveryProblems.push('polling did not recover Play after a missed SSE event'));
    assert.equal((await aliceContext.request.post(`${base}/fixture/pending`)).status(), 204);
    await alice.evaluate(() => {
      window.catalogueRequests = 0;
      const fetch = window.fetch;
      window.fetch = (input, ...options) => {
        if (String(input).startsWith('/audio/tracks')) window.catalogueRequests++;
        return fetch(input, ...options);
      };
    });
    const pendingResponse = alice.waitForResponse(response => response.url().endsWith('/download/status'));
    await alice.evaluate(() => document.dispatchEvent(new CustomEvent('htmx:afterSwap', {detail:{target:document.getElementById('content')}})));
    await pendingResponse;
    await alice.evaluate(() => new Promise(requestAnimationFrame));
    const requestCount = await alice.evaluate(() => window.catalogueRequests);
    if (requestCount > 3) recoveryProblems.push(`one poll issued ${requestCount} catalogue requests for 1000 pending tracks`);
    assert.deepEqual(recoveryProblems, [], 'availability recovery and batching');
    await alice.getByRole('link', {name: 'Settings', exact: false}).click();
    await alice.locator('#create-user-form').waitFor();
    const adminRow = alice.locator('.user-row[data-username="admin"]');
    await adminRow.locator('.user-delete button').click();
    await alice.waitForFunction(() => !document.querySelector('.user-row[data-username="admin"]'));
    await alice.waitForFunction(() => document.getElementById('bootstrap-warning').hidden);
    const unauthorized = await context.request.get(`${base}/audio/tracks`);
    assert.equal(unauthorized.status(), 401, 'deletion must revoke admin session');
    const bobContext = await browser.newContext();
    bobContext.on('page', observe);
    const bob = await bobContext.newPage();
    await signIn(bob, 'bob', 'password');
    const bobRow = alice.locator('.user-row[data-username="bob"]');
    await bobRow.locator('.user-password [name="password"]').fill('changed-password');
    await bobRow.locator('.user-password button').click();
    await alice.waitForResponse(r => r.url().endsWith('/?source=settings') && r.status() === 200);
    assert.equal((await bobContext.request.get(`${base}/audio/tracks`)).status(), 401, 'reset must revoke sessions');
    const staleTab = await aliceContext.newPage();
    const aliceID = await alice.locator('body').getAttribute('data-user-id');
    await staleTab.route('**/auth/status', route => route.fulfill({json:{id:Number(aliceID), username:'alice', bootstrap:false}}));
    await staleTab.goto(`${base}/?source=spotify`);
    await staleTab.locator('[name="headers"]').fill('authorization: Bearer alice-secret\nclient-token: alice-client');
    const switchTab = await aliceContext.newPage();
    await signIn(switchTab, 'bob', 'changed-password');
    const staleResponse = staleTab.waitForResponse(response => new URL(response.url()).pathname === '/connect');
    await staleTab.getByRole('button', {name:'Save credentials', exact:true}).click();
    assert.equal((await staleResponse).status(), 409, 'stale native forms must not mutate the new account');
    await switchTab.goto(`${base}/?source=spotify`);
    assert.equal(await switchTab.locator('.pill.connected').count(), 0, 'Alice credentials must not connect Bob');
    await staleTab.close();
    await switchTab.close();
    await signIn(alice, 'alice', 'password');
    await alice.getByRole('link', {name:'Settings', exact:false}).click();
    await alice.locator('#create-user-form').waitFor();
    const ownRow = alice.locator('.user-row[data-username="alice"]');
    await ownRow.locator('.user-password [name="password"]').fill('own-new-password');
    await ownRow.locator('.user-password button').click();
    await alice.getByRole('button', {name: 'Sign in', exact: true}).waitFor({timeout:5000});
    assert.equal((await aliceContext.request.get(`${base}/audio/tracks`)).status(), 401, 'own password reset must revoke the current session');
    await signIn(alice, 'alice', 'own-new-password');
    await alice.locator('#logout-form button').click();
    await alice.getByRole('button', {name: 'Sign in', exact: true}).waitFor();
    assert.equal((await aliceContext.request.get(`${base}/audio/tracks`)).status(), 401);
    assert.deepEqual(errors, [], 'browser scripts must not throw');
    console.log('PASS: login, users, shared/private lists, independent tabs, playback/navigation, themes/mobile, missed-SSE recovery, 1000-track batching, stale-account protection, deletion, reset and logout');
  } catch (error) {
    console.error('Failed at', page.url(), 'content:', await page.locator('#content').getAttribute('data-source').catch(() => 'unavailable'), 'errors:', errors);
    throw error;
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
